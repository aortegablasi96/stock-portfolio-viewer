/**
 * Bundled geographic reference data for the Allocation world map (Story #46; DDR-0019,
 * superseding DDR-0014 on the basemap).
 *
 * This module is now purely the **country centroid table**: ISO 3166-1 alpha-2 codes (the
 * `issuerCountryCode` Flex reports) → display name and centroid, so any country IBKR reports is
 * placeable and gets a readable name for its tooltip. It stays static and offline, in the spirit
 * of the categorical palette in app.css.
 *
 * The transform from allocation data to sector-segmented bubbles lives in `lib/sectorMap`
 * (Story #71), which consumes `centroidFor` from here.
 *
 * Story #89 retired this module's other half. The equirectangular projection
 * (`projectEquirectangular`, `MAP_WIDTH`/`MAP_HEIGHT`) and the ~54 KB Natural Earth land
 * silhouette both existed to draw a basemap by hand; Mapbox GL JS draws it now and owns
 * projection, so both are gone. The centroids remain because *where a country is* is still the
 * app's own data, independent of whoever renders the map beneath it.
 */

export interface Centroid {
  name: string
  lat: number
  lon: number
}

/** Centroid for an ISO alpha-2 code (case-insensitive), or undefined when unknown. */
export function centroidFor(code: string): Centroid | undefined {
  return code ? COUNTRY_CENTROIDS[code.toUpperCase()] : undefined
}

